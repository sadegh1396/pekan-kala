CREATE TABLE "Product" (
 "id" TEXT NOT NULL PRIMARY KEY,
 "name" TEXT NOT NULL, "en" TEXT NOT NULL, "price" INTEGER NOT NULL,
 "old" INTEGER, "category" TEXT NOT NULL, "range" TEXT NOT NULL,
 "power" TEXT NOT NULL, "tag" TEXT NOT NULL, "color" TEXT NOT NULL,
 "image" TEXT NOT NULL DEFAULT '', "stock" INTEGER NOT NULL DEFAULT 0,
 "active" BOOLEAN NOT NULL DEFAULT true
);
CREATE TABLE "Admin" (
 "id" TEXT NOT NULL PRIMARY KEY, "email" TEXT NOT NULL,
 "passwordHash" TEXT NOT NULL, "role" TEXT NOT NULL DEFAULT 'ADMIN'
);
CREATE UNIQUE INDEX "Admin_email_key" ON "Admin"("email");
CREATE TABLE "Session" (
 "tokenHash" TEXT NOT NULL PRIMARY KEY, "adminId" TEXT NOT NULL, "expiresAt" DATETIME NOT NULL,
 CONSTRAINT "Session_adminId_fkey" FOREIGN KEY ("adminId") REFERENCES "Admin"("id") ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE TABLE "LoginAttempt" (
 "key" TEXT NOT NULL PRIMARY KEY, "count" INTEGER NOT NULL DEFAULT 0, "resetAt" DATETIME NOT NULL
);
CREATE TABLE "Order" (
 "id" TEXT NOT NULL PRIMARY KEY, "customer" TEXT NOT NULL, "phone" TEXT NOT NULL,
 "address" TEXT NOT NULL, "total" INTEGER NOT NULL, "status" TEXT NOT NULL DEFAULT 'PENDING',
 "createdAt" DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE "OrderItem" (
 "id" TEXT NOT NULL PRIMARY KEY, "orderId" TEXT NOT NULL, "productId" TEXT NOT NULL,
 "name" TEXT NOT NULL, "price" INTEGER NOT NULL, "quantity" INTEGER NOT NULL,
 CONSTRAINT "OrderItem_orderId_fkey" FOREIGN KEY ("orderId") REFERENCES "Order"("id") ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE TABLE "Reservation" (
 "id" TEXT NOT NULL PRIMARY KEY, "orderId" TEXT NOT NULL, "requestedDate" TEXT NOT NULL,
 "status" TEXT NOT NULL DEFAULT 'PENDING', "createdAt" DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT "Reservation_orderId_fkey" FOREIGN KEY ("orderId") REFERENCES "Order"("id") ON DELETE RESTRICT ON UPDATE CASCADE
);
CREATE UNIQUE INDEX "Reservation_orderId_key" ON "Reservation"("orderId");
